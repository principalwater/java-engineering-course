-- Старые заказы не имеют подтверждения списания: миграция не превращает их в выручку.
ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS status VARCHAR(24) NOT NULL DEFAULT 'LEGACY_UNPAID' CHECK (status IN ('LEGACY_UNPAID', 'PAID'));
ALTER TABLE purchase_orders ADD COLUMN IF NOT EXISTS payment_id UUID CHECK ((status = 'PAID' AND payment_id IS NOT NULL) OR (status = 'LEGACY_UNPAID' AND payment_id IS NULL));
CREATE UNIQUE INDEX IF NOT EXISTS order_payment_idx ON purchase_orders(payment_id);
CREATE TABLE IF NOT EXISTS checkout_intents (
    id UUID PRIMARY KEY,
    cart_id UUID NOT NULL REFERENCES shopping_carts(id),
    active_cart_id UUID UNIQUE REFERENCES shopping_carts(id),
    payer_id UUID NOT NULL,
    amount_minor BIGINT NOT NULL CHECK (amount_minor BETWEEN 1 AND 1000000000000000),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PREPARED', 'CONFIRMED', 'DECLINED')),
    order_id BIGINT REFERENCES purchase_orders(id),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CHECK ((status = 'PREPARED' AND active_cart_id IS NOT NULL AND active_cart_id = cart_id) OR (status <> 'PREPARED' AND active_cart_id IS NULL)),
    CHECK ((status = 'CONFIRMED' AND order_id IS NOT NULL) OR (status <> 'CONFIRMED' AND order_id IS NULL))
);
CREATE INDEX IF NOT EXISTS intent_recovery_idx ON checkout_intents(status, created_at);
CREATE INDEX IF NOT EXISTS intent_cart_idx ON checkout_intents(cart_id, created_at DESC);
CREATE TABLE IF NOT EXISTS checkout_intent_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id UUID NOT NULL REFERENCES checkout_intents(id),
    line_number INTEGER NOT NULL,
    product_id BIGINT NOT NULL,
    sku VARCHAR(64) NOT NULL,
    title VARCHAR(120) NOT NULL,
    image VARCHAR(32) NOT NULL,
    price BIGINT NOT NULL CHECK (price BETWEEN 1 AND 1000000),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    UNIQUE(intent_id, line_number)
);
